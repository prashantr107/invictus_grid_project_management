"""Attachment storage behind a small interface (SRS §3.9).

The database stores only metadata (`storage_key`, `original_name`, MIME type,
size). Bytes live in a pluggable `Storage` backend so the local filesystem used
today can be swapped for object storage later without touching the API or
service layer. Storage keys are always server-generated, so a client-supplied
name can never influence the path on disk.
"""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path
from typing import Protocol
from uuid import uuid4

from app.core.config import get_settings


class Storage(Protocol):
    def save(self, data: bytes, *, suffix: str = "") -> str: ...

    def read(self, storage_key: str) -> bytes: ...

    def delete(self, storage_key: str) -> None: ...


class LocalStorage:
    """Filesystem-backed storage rooted at a single directory."""

    def __init__(self, root: Path) -> None:
        self.root = Path(root)

    def _path(self, storage_key: str) -> Path:
        # Keys are generated by `save`, but validate anyway so a corrupted or
        # malicious key can never escape the storage root.
        if not storage_key or any(char not in "0123456789abcdef" for char in storage_key.split(".", 1)[0]):
            raise ValueError("Invalid storage key")
        target = (self.root / storage_key).resolve()
        if self.root.resolve() not in target.parents:
            raise ValueError("Invalid storage key")
        return target

    def save(self, data: bytes, *, suffix: str = "") -> str:
        self.root.mkdir(parents=True, exist_ok=True)
        key = f"{uuid4().hex}{suffix}"
        self._path(key).write_bytes(data)
        return key

    def read(self, storage_key: str) -> bytes:
        return self._path(storage_key).read_bytes()

    def delete(self, storage_key: str) -> None:
        try:
            self._path(storage_key).unlink()
        except FileNotFoundError:
            pass


@lru_cache
def get_storage() -> Storage:
    return LocalStorage(Path(get_settings().storage_dir))
