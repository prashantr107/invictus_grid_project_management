"""Schema/migration regression tests.

Run the full Alembic chain against a throwaway SQLite database, then assert the
migrated schema has not drifted from the SQLAlchemy models (`alembic check`) and
that the unique indexes for `users.email` / `projects.key` are genuinely unique
(the model declares `unique=True, index=True`; the migrations used to instead
create a unique constraint plus a redundant non-unique index).

Run from backend/:  python -m pytest tests/test_migrations.py -v
"""

from pathlib import Path

from alembic import command
from alembic.config import Config
from sqlalchemy import create_engine, inspect

BACKEND_DIR = Path(__file__).resolve().parents[1]


def _config(db_path: Path, monkeypatch) -> Config:
    monkeypatch.setenv("DATABASE_URL", f"sqlite+pysqlite:///{db_path}")
    config = Config(str(BACKEND_DIR / "alembic.ini"))
    config.set_main_option("script_location", str(BACKEND_DIR / "migrations"))
    return config


def test_migrated_schema_matches_models(tmp_path, monkeypatch):
    db_path = tmp_path / "migration_check.db"
    config = _config(db_path, monkeypatch)

    command.upgrade(config, "head")
    # Raises alembic.util.exc.AutogenerateDiffsDetected if models and DB differ.
    command.check(config)


def test_unique_indexes_match_model_intent(tmp_path, monkeypatch):
    db_path = tmp_path / "migration_indexes.db"
    config = _config(db_path, monkeypatch)
    command.upgrade(config, "head")

    inspector = inspect(create_engine(f"sqlite+pysqlite:///{db_path}"))

    email_indexes = inspector.get_indexes("users")
    assert [i["name"] for i in email_indexes if i["column_names"] == ["email"]] == ["ix_users_email"]
    assert next(i for i in email_indexes if i["name"] == "ix_users_email")["unique"]

    key_indexes = inspector.get_indexes("projects")
    assert [i["name"] for i in key_indexes if i["column_names"] == ["key"]] == ["ix_projects_key"]
    assert next(i for i in key_indexes if i["name"] == "ix_projects_key")["unique"]


def test_downgrade_to_base_is_clean(tmp_path, monkeypatch):
    db_path = tmp_path / "migration_downgrade.db"
    config = _config(db_path, monkeypatch)

    command.upgrade(config, "head")
    command.downgrade(config, "base")

    inspector = inspect(create_engine(f"sqlite+pysqlite:///{db_path}"))
    assert inspector.get_table_names() == ["alembic_version"]


def test_task_status_index_created(tmp_path, monkeypatch):
    db_path = tmp_path / "migration_task_status.db"
    config = _config(db_path, monkeypatch)
    command.upgrade(config, "head")

    inspector = inspect(create_engine(f"sqlite+pysqlite:///{db_path}"))
    index_names = {i["name"] for i in inspector.get_indexes("tasks")}
    assert "ix_tasks_status" in index_names
    columns = {c["name"] for c in inspector.get_columns("audit_logs")}
    assert "target_id" in columns
